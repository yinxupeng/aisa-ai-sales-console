import assert from "node:assert/strict";
import { defaultReportSchedule, validateReportSchedule, nextReportRun, interpretScheduleRequest, simulateReportRun, describeReportSchedule } from "../src/data/reportSchedules.js";
import { seedReportWorkspace } from "../src/data/salesReports.js";
const now = new Date("2026-10-29T08:00:00+08:00");
const daily = defaultReportSchedule(now);
assert.equal(nextReportRun(daily, now), "2026-10-29 09:00");
assert.equal(nextReportRun(daily, new Date("2026-10-29T09:00:00+08:00")), "2026-10-30 09:00", "已经到达的时间不再显示为下次执行");
assert.equal(nextReportRun({ ...daily, times: ["18:00", "09:00"] }, new Date("2026-10-29T12:00:00+08:00")), "2026-10-29 18:00");
assert.equal(nextReportRun({ ...daily, frequency: "weekly", weekdays: [1, 5] }, now), "2026-10-30 09:00");
assert.equal(nextReportRun({ ...daily, frequency: "interval", intervalDays: 3, anchorDate: "2026-10-28" }, now), "2026-10-31 09:00");
assert.equal(nextReportRun({ ...daily, enabled: false }, now), null);
assert.equal(nextReportRun({ ...daily, times: [""] }, now), null);
assert.equal(nextReportRun({ ...daily, times: ["00:05"] }, new Date("2026-10-29T15:59:00Z")), "2026-10-30 00:05", "跨北京时间午夜正确计算");
assert.throws(() => validateReportSchedule({ ...daily, times: ["09:00", "09:00"] }), /不能重复/);
assert.throws(() => validateReportSchedule({ ...daily, times: ["24:00"] }), /有效/);
assert.throws(() => validateReportSchedule({ ...daily, frequency: "weekly", weekdays: [] }), /执行日/);
assert.throws(() => validateReportSchedule({ ...daily, frequency: "interval", intervalDays: 0 }), /1—30/);
assert.throws(() => validateReportSchedule({ ...daily, frequency: "interval", anchorDate: "2026-02-31" }), /无效/);
assert.equal(interpretScheduleRequest("每天上午9点生成", now).schedule.times[0], "09:00");
assert.equal(interpretScheduleRequest("每天下午3点半生成", now).schedule.times[0], "15:30");
assert.equal(interpretScheduleRequest("每周一18:00生成", now).schedule.frequency, "weekly");
assert.equal(interpretScheduleRequest("每隔3天09:00生成", now).schedule.intervalDays, 3);
assert.ok(interpretScheduleRequest("每天生成", now).error);
assert.equal(interpretScheduleRequest("生成最近7天沟通报表", now), null);
const report = { ...seedReportWorkspace(["wecom-li"]).reports[0], schedule: daily };
const before = JSON.stringify(report);
const success = simulateReportRun(report, ["wecom-li"], now);
assert.equal(success.status, "成功"); assert.ok(success.result); assert.equal(success.trigger, "手动模拟");
assert.equal(simulateReportRun(report, [], now).status, "失败");
assert.equal(JSON.stringify(report), before, "执行记录不能改写已有报表快照");
assert.equal(describeReportSchedule(daily), "每天 09:00");
console.log("REPORT_SCHEDULES_OK");
