import assert from "node:assert/strict";
import { computeSalesReport, interpretReportRequest, seedReportWorkspace } from "../src/data/salesReports.js";
import { withOrderQueryDemo, orderDemoSessionId } from "../src/data/salesAssistantDemo.js";
import { migrateReportArtifacts } from "../src/data/salesReportArtifacts.js";
const definition = interpretReportRequest("查询昨天生成多少订单").definition;
assert.equal(definition.presentation, "orderQuery");
const result = computeSalesReport(definition, []);
assert.equal(result.summary.salesOrders, 22);
assert.equal(result.summary.gmv, 106500);
assert.equal(result.summary.paidStudents, 22);
assert.equal(result.summary.peakOrders, 14);
assert.equal(result.summary.excludedOrders, 12);
assert.equal(result.summary.excludedGmv, 68940);
assert.equal(result.summary.primaryProductOrders, 20);
assert.equal(result.metrics[0][1], 22, "交付角色订单不能加回销售指标");
assert.equal(result.rows.length, 22);
assert.equal(result.groups.length, 12);
assert.equal(result.rows.reduce((sum, item) => sum + item.amount, 0), 106500);
assert.equal(result.groups.reduce((sum, item) => sum + item.amount, 0), 106500);
assert.equal(result.groups.reduce((sum, item) => sum + item.orders, 0), 22);
assert.equal(result.rows.filter((item) => item.paidAt >= '20:30:00' && item.paidAt <= '21:00:00').length, 14);
assert.equal(result.groups.find((item) => item.owner === '高曌').amount, 19860);
assert.equal(result.groups.find((item) => item.owner === '司法').orders, 4);
assert.ok(result.rows.every((item) => /^\d{3}\*{4}\d{4}$/.test(item.phone)));
const legacy = { sessions: [{ messages: [{ orderReport: { ...result, rows: [], groups: [] } }] }], reports: [], orderDemoInitialized: true };
assert.equal(withOrderQueryDemo(legacy).sessions[0].messages[0].orderReport.rows.length, 22, "已有演示记录也应补齐新明细");
const workspace = withOrderQueryDemo(seedReportWorkspace([]));
const demo = workspace.sessions.find((item) => item.id === orderDemoSessionId);
assert.equal(demo.messages.length, 2);
assert.equal(demo.pageGenerated, false);
assert.equal(demo.messages[1].orderReport.summary.gmv, 106500);
assert.equal(migrateReportArtifacts(workspace, []).sessions[0].messages[1].artifact, undefined, "查询完成不自动生成页面文件");
assert.equal(workspace.reports.length, 4, "不自动保存报表");
assert.equal(withOrderQueryDemo(workspace), workspace);
console.log("ORDER_QUERY_DEMO_OK");
