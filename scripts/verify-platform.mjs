import assert from 'node:assert/strict';
import { build } from 'esbuild';

const result = await build({entryPoints: ['src/shared/platformDomain.ts'], bundle: true, write: false, platform: 'node', format: 'esm'});
const domain = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const { validateLicense, assignSeats, syncLicense, serviceStatus, seatUsage, normalizeLicense, normalizeWecomAccount } = domain;
assert.equal(typeof validateLicense, 'function', '需要授权校验函数');
const license = {total: 2, expiresAt: '2027-09-01', status: 'active'};
const company = {id: 'a', name: 'A', license, appliedLicense: {...license}, accounts: [{key:'a1', aiSeatEnabled:true, hosted:true}, {key:'a2', aiSeatEnabled:false}, {key:'a3', aiSeatEnabled:false}]};
assert.equal(serviceStatus(license, '2026-09-14'), 'active');
assert.equal(serviceStatus(license, '2027-09-02'), 'expired');
assert.equal(serviceStatus({...license, startsAt:'2027-08-01'}, '2026-08-31'), 'active', '旧数据的开始时间不再限制授权生效');
assert.doesNotThrow(() => validateLicense(license, company.accounts), '配置席位只需要数量与到期时间');
assert.deepEqual(normalizeLicense({...license,startsAt:'2027-08-01'}), license, '旧授权迁移后只保留数量、到期时间和状态');
assert.equal(serviceStatus({...license,status:'suspended'}, '2026-09-14'), 'suspended');
assert.throws(() => validateLicense({...license,total:0}, company.accounts), /已分配/);
assert.throws(() => validateLicense({...license,total:1.5}, []), /整数/);
assert.throws(() => validateLicense({...license,expiresAt:''}, []), /到期/);
assert.throws(() => validateLicense({...license,expiresAt:'2026-02-30'}, []), /到期/);
assert.equal(serviceStatus(license, '2027-09-01'), 'expiring', '到期当天仍有效');
const allocated = assignSeats(company, ['a2'], true, '2026-09-14');
assert.equal(seatUsage(allocated).remaining, 0);
assert.equal(company.accounts[1].aiSeatEnabled, false, '纯函数不得修改原企业');
const lateAllocated = assignSeats(company, ['a2'], true, '2027-08-20');
assert.equal(allocated.appliedLicense.expiresAt, lateAllocated.appliedLicense.expiresAt, '不同分配日期共享企业到期时间');
assert.equal(lateAllocated.appliedLicense.expiresAt, '2027-09-01');
assert.ok(!('aiSeatOpenedAt' in allocated.accounts[1]), '分配席位不再产生账号开通日期');
assert.deepEqual(normalizeWecomAccount({key:'legacy',aiSeatEnabled:true,hosted:true,aiSeatOpenedAt:'2026-01-01',aiSeatClosedAt:''}), {key:'legacy',aiSeatEnabled:true,hosted:true}, '历史账号保留配置并移除独立开通日期');
assert.throws(() => assignSeats(allocated, ['a3'], true, '2026-09-14'), /席位已用完/);
assert.throws(() => assignSeats(company, ['other-company-account'], true, '2026-09-14'), /不存在/);
assert.throws(() => assignSeats(company, ['a2'], true, '2027-09-02'), /服务/);
const released = assignSeats(allocated, ['a1'], false, '2027-09-02');
assert.equal(released.accounts[0].hosted, false);
assert.ok(!('aiSeatClosedAt' in released.accounts[0]), '释放操作时间由操作日志记录');
assert.equal(seatUsage(released).used, 1);
const pending = {...company, license:{...license,total:5}};
assert.equal(seatUsage(pending).total, 2, '同步前仍使用旧授权');
assert.equal(seatUsage(syncLicense(pending)).total, 5);
const renewed=syncLicense({...allocated,license:{...license,expiresAt:'2028-09-01'}});
assert.equal(renewed.appliedLicense.expiresAt, '2028-09-01', '续期同步统一修改企业到期日');
assert.deepEqual(renewed.accounts.map(a=>a.aiSeatEnabled), allocated.accounts.map(a=>a.aiSeatEnabled), '续期不改变账号分配，不创建新批次');
assert.throws(() => syncLicense({...allocated, license:{...license,total:1}}), /已分配/);
assert.throws(() => assignSeats({...company,appliedLicense:{...license,status:'suspended'}}, ['a2'], true, '2026-09-14'), /服务/);
console.log('PLATFORM_RULES_OK: 额度、有效期、企业隔离、批量分配和授权同步');
