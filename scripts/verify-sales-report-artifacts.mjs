import assert from "node:assert/strict";
import { createReportArtifact, migrateReportArtifacts } from "../src/data/salesReportArtifacts.js";
import { computeSalesReport, defaultReportDefinition } from "../src/data/salesReports.js";
const definition = { ...defaultReportDefinition };
const result = computeSalesReport(definition, ["wecom-li"]);
const artifact = createReportArtifact({ definition, result });
assert.equal(artifact.kind, "report");
assert.ok(artifact.title.endsWith(".report"));
definition.days = 30; result.metrics[0][1] = -1;
assert.equal(artifact.definition.days, 7, "历史入口需指向该次生成定义");
assert.notEqual(artifact.result.metrics[0][1], -1, "历史报表快照不能被后续结果覆盖");
assert.equal(createReportArtifact({ demoPage: "intentAnalysis" }).kind, "intentAnalysis");
assert.equal(createReportArtifact({}), null);
const workspace = { sessions: [{ id: "old", definition: { ...defaultReportDefinition }, messages: [{ role: "assistant", text: "已按旧范围整理" }, { role: "assistant", text: "已按最近7天整理" }, { role: "assistant", status: "stopped", text: "已停止生成" }] }] };
const migrated = migrateReportArtifacts(workspace, ["wecom-li"]);
assert.equal(migrated.sessions[0].messages[0].artifact, undefined, "没有旧快照时不应虚构每条历史消息的结果");
assert.ok(migrated.sessions[0].messages[1].artifact);
assert.equal(migrated.sessions[0].messages[2].artifact, undefined);
assert.equal(workspace.sessions[0].messages[1].artifact, undefined);
assert.equal(migrateReportArtifacts(migrated, ["wecom-li"]).sessions[0], migrated.sessions[0]);
console.log("SALES_REPORT_ARTIFACTS_OK");
