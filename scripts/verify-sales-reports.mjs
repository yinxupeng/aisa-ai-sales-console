import assert from "node:assert/strict";
import { reportDemoUsers, reportAccounts, defaultReportDefinition, computeSalesReport, interpretReportRequest, seedReportWorkspace, workspaceStorageKey } from "../src/data/salesReports.js";
const keys = reportAccounts.map((item) => item.key);
assert.equal(reportDemoUsers.length, 291);
const result = computeSalesReport(defaultReportDefinition, keys);
assert.equal(result.metrics[0][1], 291);
assert.equal(result.groups.reduce((sum, row) => sum + row.users, 0), result.rows.length);
assert.equal(result.groups.reduce((sum, row) => sum + row.active, 0), result.metrics[1][1]);
assert.equal(result.chart.reduce((sum, row) => sum + row.value, 0), result.metrics[1][1]);
assert.ok(result.rows.every((row) => row.daysAgo < 7));
const scoped = computeSalesReport({ ...defaultReportDefinition, days: 30, role: "销售A类", stage: "第三节课" }, ["wecom-li"]);
assert.ok(scoped.rows.every((row) => row.accountKey === "wecom-li" && row.stage === "第三节课" && row.role === "销售A类"));
assert.equal(scoped.period, "2026-09-29—2026-10-28");
assert.equal(computeSalesReport(defaultReportDefinition, []).rows.length, 0);
const initial = interpretReportRequest("分析最近30天各销售的报名转化").definition;
assert.equal(initial.type, "conversion"); assert.equal(initial.days, 30);
const adjusted = interpretReportRequest("只看第三节课，按角色分组", initial).definition;
assert.equal(adjusted.type, "conversion"); assert.equal(adjusted.days, 30); assert.equal(adjusted.stage, "第三节课"); assert.equal(adjusted.group, "role");
assert.ok(interpretReportRequest("分析最近90天沟通").error);
assert.ok(interpretReportRequest("查其他企业的销售").error);
assert.ok(interpretReportRequest("到课情况").error);
assert.ok(interpretReportRequest("你好").error);
const intent = computeSalesReport({ ...defaultReportDefinition, type: "intent" }, keys);
assert.equal(intent.chart.reduce((sum, row) => sum + row.value, 0), intent.rows.length);
assert.equal(seedReportWorkspace(keys).reports.length, 4);
assert.notEqual(workspaceStorageKey("a", "company", keys), workspaceStorageKey("b", "company", keys));
assert.notEqual(workspaceStorageKey("a", "company", keys), workspaceStorageKey("a", "company", [keys[0]]));
console.log("SALES_REPORTS_OK");
