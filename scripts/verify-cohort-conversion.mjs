import assert from "node:assert/strict";
import { cohortConversionDefinition } from "../src/data/cohortConversionReport.js";
import { computeSalesReport, reportAccounts, interpretReportRequest, seedReportWorkspace } from "../src/data/salesReports.js";
import { withCohortConversionDemo, cohortDemoSessionId } from "../src/data/salesAssistantDemo.js";
import { migrateReportArtifacts } from "../src/data/salesReportArtifacts.js";
const keys = reportAccounts.map((item) => item.key);
const report = computeSalesReport(cohortConversionDefinition, keys);
assert.equal(report.rows.length, 70);
assert.equal(new Set(report.rows.map((row) => row.date)).size, 7);
assert.equal(new Set(report.rows.map((row) => row.cohort)).size, 14);
assert.equal(report.groups.length, 5);
assert.equal(report.groups.reduce((sum, row) => sum + row.participants, 0), report.metrics[0][1]);
assert.equal(report.groups.reduce((sum, row) => sum + row.enrolled, 0), report.metrics[1][1]);
assert.equal(report.metrics[2][1], `${(report.metrics[1][1] / report.metrics[0][1] * 100).toFixed(1)}%`);
assert.ok(report.rows.every((row) => row.enrolled <= row.participants && row.rate === Number((row.enrolled / row.participants * 100).toFixed(1))));
assert.equal(computeSalesReport(cohortConversionDefinition, ["wecom-li"]).rows.length, 14);
assert.equal(computeSalesReport(cohortConversionDefinition, []).metrics[2][1], "0.0%");
assert.equal(interpretReportRequest("最近一周每天每期次体验课转化率，分销售看").definition.presentation, "cohortConversion");
assert.ok(interpretReportRequest("最近30天体验课转化率").error);
const state = withCohortConversionDemo(seedReportWorkspace(keys), keys);
const demo = state.sessions.find((item) => item.id === cohortDemoSessionId);
assert.equal(demo.messages.length, 4);
assert.ok(demo.messages[1].chatReport);
assert.equal(demo.messages[1].artifact, undefined, "第一次只输出聊天数据");
assert.ok(demo.messages[2].text.includes("生成一个页面"));
assert.deepEqual(demo.messages[3].artifact.result.rows, demo.messages[1].chatReport.rows, "页面与聊天保持同一份数据");
assert.equal(state.reports.length, 4, "演示生成不自动保存到报表列表");
assert.ok(!demo.schedule, "演示不自动创建定时任务");
assert.equal(withCohortConversionDemo(state, keys), state);
const dataOnlyState = { sessions: [{ definition: cohortConversionDefinition, pageGenerated: false, messages: [{ role: "assistant", text: "已整理数据", chatReport: report }] }] };
assert.equal(migrateReportArtifacts(dataOnlyState, keys).sessions[0].messages[0].artifact, undefined, "刷新后也不能提前生成页面入口");
console.log("COHORT_CONVERSION_OK");
