import assert from "node:assert/strict";
import { listAnalysisHistory, changeAnalysisHistory } from "../src/data/analysisHistory.js";
import { withIntentAnalysisDemo, intentDemoSessionId } from "../src/data/salesAssistantDemo.js";
const rows = [{ id: "a", title: "旧分析", updatedAt: "2026-10-28 09:00" }, { id: "b", title: "新分析", updatedAt: "2026-10-29 09:00" }];
const before = JSON.stringify(rows);
const pinned = changeAnalysisHistory(rows, "a", "pin");
assert.equal(listAnalysisHistory(pinned)[0].id, "a");
assert.equal(listAnalysisHistory(changeAnalysisHistory(pinned, "a", "pin"))[0].id, "b");
assert.equal(changeAnalysisHistory(rows, "a", "rename", "  家长意向报表  ")[0].title, "家长意向报表");
assert.throws(() => changeAnalysisHistory(rows, "a", "rename", " "), /名称/);
const archived = changeAnalysisHistory(pinned, "a", "archive");
assert.equal(listAnalysisHistory(archived).length, 1);
assert.equal(listAnalysisHistory(archived, true)[0].id, "a");
assert.equal(archived[0].pinned, false);
assert.equal(listAnalysisHistory(changeAnalysisHistory(archived, "a", "restore")).length, 2);
assert.equal(changeAnalysisHistory(rows, "a", "delete").length, 1);
assert.equal(JSON.stringify(rows), before);
const migrated = withIntentAnalysisDemo({ sessions: rows, reports: [] });
assert.equal(migrated.sessions[0].id, intentDemoSessionId);
assert.equal(migrated.sessions[0].demoPage, "intentAnalysis");
assert.equal(migrated.sessions.length, 3);
assert.equal(withIntentAnalysisDemo(migrated), migrated, "演示记录只补充一次");
const deleted = { ...migrated, sessions: changeAnalysisHistory(migrated.sessions, intentDemoSessionId, "delete") };
assert.equal(withIntentAnalysisDemo(deleted).sessions.length, 2, "删除后不能自动复活演示");
assert.equal(rows.length, 2);
console.log("ANALYSIS_HISTORY_AND_DEMO_OK");
