import assert from "node:assert/strict";
import * as model from "../src/data/intentChatConfig.js";
assert.equal(typeof model.createIntentChatState, "function");
const state = model.createIntentChatState();
assert.equal(state.taskEnabled, false, "方案二定时分析默认关闭");
assert.equal(model.validateIntentChatDraft(state.draft), "");
assert.deepEqual(state.draft.dataSources, ["platform", "business"], "默认选中平台数据和业务数据");
assert.equal(model.validateIntentChatDraft({ ...state.draft, dataSources: ["platform"] }), "");
assert.equal(model.validateIntentChatDraft({ ...state.draft, dataSources: ["business"] }), "");
assert.ok(model.validateIntentChatDraft({ ...state.draft, dataSources: [] }), "至少保留一种数据来源");
assert.ok(model.validateIntentChatDraft({ ...state.draft, dataSources: ["unknown"] }));
assert.throws(() => model.enableIntentChatDemo(state), /试跑/);
const tried = model.tryIntentChatDemo(state);
assert.ok(tried.trial.rows.length > 0);
const enabled = model.enableIntentChatDemo(tried);
assert.equal(enabled.taskEnabled, true, "确认模拟启用后开启任务");
assert.equal(typeof model.setIntentChatTaskEnabled, "function");
assert.throws(() => model.setIntentChatTaskEnabled(state, true), /启用/);
const paused = model.setIntentChatTaskEnabled(enabled, false);
assert.equal(paused.taskEnabled, false);
assert.deepEqual(paused.active, enabled.active, "停止任务不清空启用方案和历史快照");
assert.deepEqual(paused.draft, enabled.draft, "停止任务仍保留配置");
assert.equal(model.setIntentChatTaskEnabled(paused, true).taskEnabled, true);
assert.equal(enabled.active.version, 1);
const edited = model.changeIntentChatDraft(enabled, { ...enabled.draft, dailyTimes: ["10:00"] });
assert.equal(edited.trial, null);
assert.equal(edited.active.config.dailyTimes[0], "09:00", "编辑不能影响已启用快照");
assert.throws(() => model.enableIntentChatDemo(edited), /试跑/);
assert.equal(model.enableIntentChatDemo(model.tryIntentChatDemo(edited)).active.version, 2);
const blank = { ...state.draft, prompt: " " };
assert.ok(model.validateIntentChatDraft(blank));
assert.ok(model.validateIntentChatDraft({ ...state.draft, dailyTimes: ["09:00", "09:00"] }));
assert.ok(model.validateIntentChatDraft({ ...state.draft, stages: [] }));
assert.ok(state.draft.prompt.includes("分档标准") && state.draft.prompt.includes("数据来源") && state.draft.prompt.includes("输出要求"));
assert.notEqual(model.intentChatStorageKey, "sales-ai-intent-analysis-config");
const tampered = { ...tried, draft: { ...tried.draft, prompt: "新要求" } };
assert.throws(() => model.enableIntentChatDemo(tampered), /试跑/);
assert.equal(state.active, null, "试跑和启用均不能修改传入状态");
assert.equal(typeof model.appendIntentChatRequirements, "function");
assert.equal(model.appendIntentChatRequirements("原有约束", "新要求"), "原有约束\n新要求");
assert.throws(() => model.appendIntentChatRequirements("原有约束".repeat(12500), "新增要求"), /50000/);
assert.equal(model.appendIntentChatRequirements("a".repeat(49998), "b").length, 50000);
assert.ok(model.validateIntentChatDraft({ ...state.draft, prompt: "a".repeat(50001) }));
const legacyDraft = { ...state.draft, prompt: undefined, requirements: "必须保留的原分析要求", tiers: [{ level: 3, name: "预约意向", criteria: "客户主动预约儿童心理支持服务" }] };
assert.equal(typeof model.migrateIntentChatDraft, "function");
const migrated = model.migrateIntentChatDraft(legacyDraft);
assert.ok(migrated.prompt.includes("必须保留的原分析要求") && migrated.prompt.includes("预约意向") && migrated.prompt.includes("客户主动预约儿童心理支持服务"));
assert.equal(migrated.requirements, undefined);
assert.equal(migrated.tiers, undefined);
assert.deepEqual(model.migrateIntentChatDraft(migrated), migrated, "已编辑的完整提示词不重复整理或覆盖");
const beforeSources = { ...state.draft };
delete beforeSources.dataSources;
assert.deepEqual(model.migrateIntentChatDraft(beforeSources).dataSources, ["platform", "business"], "旧草稿补齐默认来源");
const scoped = model.changeIntentChatDraft(enabled, { ...enabled.draft, dataSources: ["platform"] });
assert.equal(scoped.trial, null, "修改来源需要重新试跑");
assert.deepEqual(scoped.active.config.dataSources, ["platform", "business"], "修改来源不改变已启用快照");
console.log("INTENT_CHAT_CONFIG_OK");
