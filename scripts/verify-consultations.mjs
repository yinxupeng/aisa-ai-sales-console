import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({entryPoints:['src/shared/consultationDomain.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const d=await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const input={name:' 张女士 ',phone:'13800001234',company:'示例企业',expectedSeats:10,needs:'希望了解产品'};
const first=d.addConsultation([],input,'request-1','2026-11-08T12:00:00.000Z');
assert.equal(first.length,1);assert.equal(first[0].name,'张女士');assert.equal(first[0].status,'pending');
assert.equal(d.addConsultation(first,input,'request-1','2026-11-08T12:01:00.000Z').length,1,'同一提交凭据幂等');
assert.throws(()=>d.addConsultation([], {...input,phone:'123'},'x','now'),/手机号/);
assert.throws(()=>d.addConsultation([], {...input,name:' '},'x','now'),/姓名/);
assert.throws(()=>d.addConsultation([], {...input,expectedSeats:-1},'x','now'),/账号数/);
assert.throws(()=>d.assertCanOpenEnterprise(first[0]),/成交/);
const followed=d.followConsultation(first[0],{status:'won',ownerId:'op-1',note:'客户已确认购买'},'客服','now');
assert.equal(followed.history.length,1);assert.equal(first[0].history.length,0);assert.equal(followed.status,'won');
assert.doesNotThrow(()=>d.assertCanOpenEnterprise(followed));
const linked=d.linkConsultation(followed,'enterprise-1');
assert.equal(linked.enterpriseId,'enterprise-1');assert.throws(()=>d.assertCanOpenEnterprise(linked),/已关联/);
assert.throws(()=>d.followConsultation(linked,{status:'invalid',ownerId:'op-1',note:'改为无效'},'客服','now'),/已开通/);
assert.equal(d.validFormUrl('https://example.com/consultation.html'),true);
for(const bad of ['javascript:alert(1)','data:text/html,test','ftp://example.com','not a url','https://user:secret@example.com']) assert.equal(d.validFormUrl(bad),false);
console.log('CONSULTATION_RULES_OK');
