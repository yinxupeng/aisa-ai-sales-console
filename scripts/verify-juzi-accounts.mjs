import assert from "node:assert/strict";
import { defaultJuziAccounts, maskJuziAppKey, saveJuziAccount, setJuziAccountActive, deleteJuziAccount, validateJuziAccount } from "../src/data/juziChannelAccounts.js";

const accounts = structuredClone(defaultJuziAccounts);
const values = { label: "观心-顾问测试组", baseUrl: "https://example.com/stream-api/", appKey: "demo-key-for-tests-1234" };
assert.deepEqual(validateJuziAccount(values, accounts), {});
assert.ok(validateJuziAccount({ ...values, label: " " }, accounts).label);
assert.ok(validateJuziAccount({ ...values, baseUrl: "javascript:alert(1)" }, accounts).baseUrl);
assert.ok(validateJuziAccount({ ...values, baseUrl: "https://name:password@example.com" }, accounts).baseUrl);
assert.ok(validateJuziAccount({ ...values, appKey: " " }, accounts).appKey);
assert.ok(validateJuziAccount({ ...values, label: accounts[0].label }, accounts).label);
assert.deepEqual(validateJuziAccount(accounts[0], accounts, accounts[0].id), {});
const added = saveJuziAccount(accounts, values);
assert.equal(added.length, accounts.length + 1);
const entry = added.at(-1);
assert.equal(entry.label, values.label);
assert.equal(entry.baseUrl, "https://example.com/stream-api");
assert.equal(entry.active, false);
assert.equal(entry.lastSyncedAt, null);
assert.equal(accounts.length, defaultJuziAccounts.length, "保存不可变更传入状态");
const activated = setJuziAccountActive(added, entry.id, true, "2026-10-22 16:00");
assert.equal(activated.at(-1).active, true);
assert.equal(activated.at(-1).lastSyncedAt, "2026-10-22 16:00");
assert.equal(activated[0].active, added[0].active, "独立激活账号，不影响其他通道");
assert.throws(() => deleteJuziAccount(activated, entry.id), /取消激活/);
const renamed = saveJuziAccount(activated, { ...values, label: "观心-新名称" }, entry.id);
assert.equal(renamed.at(-1).active, true, "只修改标识不取消激活");
const reconfigured = saveJuziAccount(activated, { ...values, appKey: "new-demo-key-5678" }, entry.id);
assert.equal(reconfigured.at(-1).active, false, "连接参数变更须重新激活");
assert.equal(reconfigured.at(-1).lastSyncedAt, null);
const deactivated = setJuziAccountActive(activated, entry.id, false);
assert.equal(deactivated.at(-1).active, false);
assert.equal(deleteJuziAccount(deactivated, entry.id).length, accounts.length);
assert.throws(() => saveJuziAccount(accounts, values, "missing"), /不存在/);
assert.throws(() => setJuziAccountActive(accounts, "missing", true), /不存在/);
assert.throws(() => deleteJuziAccount(accounts, "missing"), /不存在/);
assert.equal(maskJuziAppKey(values.appKey), "demo****1234");
assert.equal(maskJuziAppKey("short"), "********");
assert.ok(!maskJuziAppKey(values.appKey).includes(values.appKey));
assert.ok(defaultJuziAccounts.every((item) => item.appKey.startsWith("demo_")), "示例密钥不得使用真实凭据");
console.log("JUZI_CHANNEL_ACCOUNTS_OK");
