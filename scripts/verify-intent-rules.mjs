import assert from "node:assert/strict";
import { defaultIntentRules, describeIntentRule, evaluateIntentRules, filterIntentUsersByScope, validateIntentRules } from "../src/data/intentRules.js";
import { intentAnalysisUsers } from "../src/data/intentAnalysisData.js";
import * as tierRules from "../src/data/intentRules.js";

const clone = (value) => JSON.parse(JSON.stringify(value));
const base = { chatCount: 8, attendanceDays: 0, consecutiveAttendanceDays: 0, totalWatchMinutes: 0, hasIllnessKeyword: false, askedPrice: false, expressedAfterLessons123: false, expressedAfterAllLessons: false, chattedAfterLesson3: false };
const grade = (metrics) => evaluateIntentRules({ ...base, ...metrics }).level;
assert.equal(validateIntentRules(defaultIntentRules), "");
assert.equal(defaultIntentRules.length, 5);
assert.equal(grade({}), 1);
assert.equal(grade({ chatCount: 20, hasIllnessKeyword: true }), 1);
assert.equal(grade({ chatCount: 21, hasIllnessKeyword: true }), 1);
assert.equal(grade({ chatCount: 80, askedPrice: true }), 1, "单独询价不能跳入4档");
assert.equal(grade({ attendanceDays: 1 }), 2);
assert.equal(grade({ attendanceDays: 2, chattedAfterLesson3: true }), 3);
const engaged = { attendanceDays: 3, consecutiveAttendanceDays: 3, totalWatchMinutes: 40, chattedAfterLesson3: true, askedPrice: true, expressedAfterLessons123: true, expressedAfterAllLessons: true };
assert.equal(grade(engaged), 3, "40分钟不满足超过40分钟");
assert.equal(grade({ ...engaged, totalWatchMinutes: 40.01 }), 4);
assert.equal(grade({ ...engaged, totalWatchMinutes: 80 }), 4, "80分钟不满足超过80分钟");
assert.equal(grade({ ...engaged, totalWatchMinutes: 80.01 }), 5);
assert.equal(grade({ ...engaged, totalWatchMinutes: 65, askedPrice: false, expressedAfterLessons123: true }), 3, "4档所有条件为且，仅有感受未询价不能命中");
assert.equal(grade({ ...engaged, totalWatchMinutes: 65, askedPrice: true, expressedAfterLessons123: false }), 3, "4档仅询价未表达感受也不能命中");
assert.ok(defaultIntentRules.every((rule) => rule.match === "all" && rule.groups.length === 1 && rule.groups[0].match === "all"), "每档默认仅一个且关系条件组");
assert.equal(grade({ ...engaged, totalWatchMinutes: 65, askedPrice: false, expressedAfterLessons123: false }), 3);
assert.deepEqual(defaultIntentRules.map((rule) => intentAnalysisUsers.filter((user) => user.level === rule.level).length), [10, 6, 6, 10, 10], "五档合并原0、1档用户，其余演示分布不变");
assert.ok(intentAnalysisUsers.every((user) => user.levelInfo?.level === user.level), "演示档位信息必须按level关联，而不是数组下标");
assert.ok(intentAnalysisUsers.every((user) => typeof user.accountKey === "string"), "用户范围按真实企微账号关联角色，不按负责人姓名猜测");

const changed = clone(defaultIntentRules);
changed.find((rule) => rule.level === 5).groups[0].conditions.find((item) => item.field === "totalWatchMinutes").value = 100;
assert.equal(evaluateIntentRules({ ...base, ...engaged, totalWatchMinutes: 96 }, changed).level, 4);
assert.equal(defaultIntentRules[4].groups[0].conditions.find((item) => item.field === "totalWatchMinutes").value, 80, "编辑不能污染默认规则");
const eitherGroup = clone(defaultIntentRules);
eitherGroup[4].match = "any";
eitherGroup[4].groups = [
  { id: "a", match: "all", conditions: [{ id: "x", field: "chatCount", operator: "gte", value: 100 }] },
  { id: "b", match: "all", conditions: [{ id: "y", field: "askedPrice", operator: "eq", value: true }] }
];
assert.equal(evaluateIntentRules({ ...base, askedPrice: true }, eitherGroup).level, 5, "历史快照仍按当时的或关系计算");
assert.ok(validateIntentRules(eitherGroup), "新配置禁止保存多组及或关系，历史快照仍可分析");
assert.equal(evaluateIntentRules({ ...base, ...engaged, totalWatchMinutes: 96, askedPrice: undefined }).status, "missing", "高档位关键字段未知时不可贸然降档");
assert.equal(evaluateIntentRules({ ...base, attendanceDays: 1, askedPrice: undefined }).level, 2, "未知字段不影响已确定不成立的高档位");
const gaps = clone(defaultIntentRules).map((rule) => ({ ...rule, groups: [{ id: "gap", match: "all", conditions: [{ id: "impossible", field: "chatCount", operator: "eq", value: 999 }] }] }));
assert.equal(evaluateIntentRules(base, gaps).status, "unmatched", "规则空档不能默认为0档");
const invalid = clone(defaultIntentRules);
invalid[0].groups[0].conditions[0].value = null;
assert.ok(validateIntentRules(invalid));
assert.ok(validateIntentRules(defaultIntentRules.slice(0, 2)), "少于3档不可保存");
assert.equal(validateIntentRules(defaultIntentRules.slice(0, 3)), "", "允许3档");
assert.equal(validateIntentRules(defaultIntentRules.slice(0, 4)), "", "允许4档");
assert.ok(validateIntentRules([...defaultIntentRules, { ...defaultIntentRules[4], level: 6 }]), "超过5档不可保存");
assert.ok(validateIntentRules(defaultIntentRules.slice(1)), "编号必须从1开始连续");
assert.ok(!describeIntentRule(defaultIntentRules[3]).includes("或"));
assert.equal(typeof tierRules.simplifyIntentRules, "function");
const simplified = tierRules.simplifyIntentRules(eitherGroup);
assert.equal(validateIntentRules(simplified), "");
assert.equal(simplified[4].groups.length, 1);
assert.equal(simplified[4].groups[0].conditions.length, 2, "简化保留全部原条件");
assert.equal(evaluateIntentRules({ ...base, askedPrice: true }, simplified).level, 1);
assert.equal(evaluateIntentRules({ ...base, chatCount: 100, askedPrice: true }, simplified).level, 5);
assert.equal(eitherGroup[4].match, "any", "配置简化不能篡改历史快照");
assert.deepEqual(tierRules.simplifyIntentRules(simplified), simplified, "重复打开配置不能引发伪规则变更");
const groupAny = clone(defaultIntentRules);
groupAny[3].groups[0].match = "any";
assert.ok(validateIntentRules(groupAny), "仅一个条件组也不能配置为或");
const noConditions = clone(defaultIntentRules);
noConditions[0].groups[0].conditions = [];
assert.ok(validateIntentRules(noConditions), "每档至少保留一个判断条件");

assert.equal(typeof tierRules.removeIntentTier, "function", "需提供带数量限制的档位删除逻辑");
const fourTiers = tierRules.removeIntentTier(defaultIntentRules, 2);
assert.deepEqual(fourTiers.map((rule) => rule.level), [1, 2, 3, 4]);
assert.equal(fourTiers[1].label, "持续参与", "删除只移除所选档位，其他条件保留并连续编号");
assert.equal(evaluateIntentRules({ ...base, ...engaged, totalWatchMinutes: 96 }, fourTiers).level, 4);
const threeTiers = tierRules.removeIntentTier(fourTiers, 2);
assert.equal(validateIntentRules(threeTiers), "");
assert.throws(() => tierRules.removeIntentTier(threeTiers, 1), /3/);
assert.throws(() => tierRules.removeIntentTier(defaultIntentRules, 99), /不存在/);
assert.equal(defaultIntentRules.length, 5, "增删不能修改传入规则快照");
const appended = tierRules.appendIntentTier(threeTiers);
assert.equal(appended.length, 4);
assert.equal(appended[3].level, 4);
assert.ok(validateIntentRules(appended), "新档位需要明确填写名称和条件后才允许保存");
appended[3].label = "预约意向";
appended[3].groups[0].conditions[0].value = 150;
assert.equal(validateIntentRules(appended), "");
assert.equal(evaluateIntentRules({ ...base, chatCount: 151 }, appended).level, 4);
assert.equal(evaluateIntentRules({ ...base, chatCount: 150 }, appended).level, 1);
assert.throws(() => tierRules.appendIntentTier(defaultIntentRules), /5/);
assert.equal(tierRules.appendIntentTier(appended).length, 5);

const oldRules = clone(tierRules.legacyIntentRules);
assert.ok(validateIntentRules(oldRules), "旧六档只允许读取历史结果，不允许作为新配置保存");
assert.equal(validateIntentRules(oldRules, { allowLegacy: true }), "");
assert.equal(evaluateIntentRules(base, oldRules).level, 0, "历史结果继续按原六档快照计算");
const migrated = tierRules.migrateIntentRules(oldRules);
assert.equal(validateIntentRules(migrated), "");
assert.equal(evaluateIntentRules(base, migrated).level, 1);
assert.equal(oldRules.length, 6, "迁移不能篡改旧批次规则");
oldRules[0].groups[0].conditions[0].value = 1;
const migratedCustom = tierRules.migrateIntentRules(oldRules);
for (const user of intentAnalysisUsers) {
  const oldResult = evaluateIntentRules(user.metrics, oldRules);
  const result = evaluateIntentRules(user.metrics, migratedCustom);
  assert.equal(result.status, oldResult.status, "迁移保留自定义条件语义");
  assert.equal(result.level, oldResult.level === 0 ? 1 : oldResult.level);
}
const scope = { userStages: ["第三节课", "第四节课", "第5节课"], hostingStatus: "不限", historicalChatThreshold: "不限", todayChatThreshold: "不限" };
assert.equal(filterIntentUsersByScope(intentAnalysisUsers, scope).length, 42);
assert.ok(filterIntentUsersByScope(intentAnalysisUsers, { ...scope, userStages: ["第三节课"] }).every((user) => user.currentLesson === 3));
assert.ok(filterIntentUsersByScope(intentAnalysisUsers, { ...scope, hostingStatus: "已托管", todayChatThreshold: "大于5条" }).every((user) => user.hosted && user.metrics.todayChatCount > 5));
const mixed = clone(defaultIntentRules);
mixed[4].mode = "prompt";
mixed[4].prompt = "家长主动咨询儿童心理支持服务费用，并明确希望预约进一步沟通。";
mixed[4].groups[0].conditions[0].value = null;
assert.equal(validateIntentRules(mixed), "", "提示词模式不校验未启用的条件草稿");
assert.equal(describeIntentRule(mixed[4]), mixed[4].prompt);
assert.deepEqual(tierRules.simplifyIntentRules(mixed), mixed, "再次打开配置保留提示词与条件草稿");
assert.equal(evaluateIntentRules(base, mixed).status, "pending", "未接入AI时不能用条件草稿伪造提示词分档");
assert.equal(evaluateIntentRules(base, mixed).level, null, "高档待AI判断时不能降到低档");
const emptyPrompt = clone(mixed);
emptyPrompt[4].prompt = "   ";
assert.match(validateIntentRules(emptyPrompt), /5档.*提示词/);
const switchBack = clone(mixed);
switchBack[4].mode = "conditions";
assert.ok(validateIntentRules(switchBack), "切回条件模式重新校验条件草稿");
switchBack[4].groups = clone(defaultIntentRules[4].groups);
switchBack[4].prompt = "";
assert.equal(validateIntentRules(switchBack), "", "条件模式不校验未启用的提示词");
switchBack[4].mode = "invalid";
assert.ok(validateIntentRules(switchBack), "拒绝未知配置方式");
const lowerPrompt = clone(defaultIntentRules);
lowerPrompt[0] = { ...lowerPrompt[0], mode: "prompt", prompt: "尚未形成明确学习意愿。" };
assert.equal(evaluateIntentRules({ ...base, ...engaged, totalWatchMinutes: 96 }, lowerPrompt).level, 5, "高档条件命中后不受低档提示词影响");
console.log("INTENT_RULES_OK");
