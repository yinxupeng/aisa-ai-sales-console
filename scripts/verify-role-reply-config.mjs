import assert from "node:assert/strict";
import * as config from "../src/data/roleReplyConfig.js";
assert.equal(typeof config.getRoleReplyConfig, "function");
const skills = [{ key: "check", status: "启用" }, { key: "disabled", status: "停用" }];
const quietDefaults = { quietHoursEnabled: false, quietHoursStart: "00:00", quietHoursEnd: "06:00" };
assert.deepEqual(config.getRoleReplyConfig({}), { analysisConversationRounds: 100, replyQualityEnabled: false, replyQualitySkillKey: undefined, ...quietDefaults });
const saved = { analysisConversationRounds: 25, replyQualityEnabled: true, replyQualitySkillKey: "check" };
assert.deepEqual(config.getRoleReplyConfig(saved), { ...saved, ...quietDefaults });
assert.equal(config.validateRoleReplyConfig(saved, skills), "");
for (const rounds of [null, 0, -1, 1.5, 1001]) assert.ok(config.validateRoleReplyConfig({ ...saved, analysisConversationRounds: rounds }, skills));
for (const key of [undefined, "disabled", "unknown"]) assert.ok(config.validateRoleReplyConfig({ ...saved, replyQualitySkillKey: key }, skills));
assert.equal(config.validateRoleReplyConfig({ ...saved, replyQualityEnabled: false, replyQualitySkillKey: "disabled" }, skills), "");
assert.equal(config.getRoleReplyConfig({ ...saved, replyQualityEnabled: false }).replyQualitySkillKey, "check", "关闭后保留选择");
const quiet = { ...saved, quietHoursEnabled: true, quietHoursStart: "00:00", quietHoursEnd: "06:00" };
assert.equal(config.validateRoleReplyConfig(quiet, skills), "");
assert.deepEqual(config.getRoleReplyConfig(quiet), quiet, "再次编辑保留已配置时段");
assert.equal(config.validateRoleReplyConfig({ ...quiet, quietHoursStart: "22:00" }, skills), "", "支持跨午夜");
for (const invalid of [{ quietHoursStart: "" }, { quietHoursEnd: null }, { quietHoursEnd: "25:00" }, { quietHoursEnd: "00:00" }]) assert.ok(config.validateRoleReplyConfig({ ...quiet, ...invalid }, skills));
assert.equal(config.validateRoleReplyConfig({ ...quiet, quietHoursEnabled: false, quietHoursEnd: "" }, skills), "", "关闭时不校验未启用的时段");
console.log("ROLE_REPLY_CONFIG_OK");
