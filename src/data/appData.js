export function isAiGeneratedTag(value) {
  return aiGeneratedTagValues.has(value);
}

export function getTagDisplayLabel(value) {
  return isAiGeneratedTag(value) ? `${value}（AI）` : value;
}

export function groupCustomerTagValues(groups, tags = []) {
  return groups.reduce((result, group) => {
    const groupTagValues = group.tags.map((tag) => tag.value);
    result[group.key] = tags.filter((tag) => groupTagValues.includes(tag));
    return result;
  }, {});
}

export function createCustomerTagValues(selected) {
  const sourceTags = selected?.tags || [];
  return {
    customer: groupCustomerTagValues(customerTagGroups, sourceTags),
    personal: selected?.intent ? [`${intentLabelMap[selected.intent] || selected.intent}`] : []
  };
}

